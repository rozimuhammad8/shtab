def kodirovkani_tuzat(matn):
    """`?` ga aylanib qolgan Q/G'/H/O' harflarini tiklaydi."""
    if '?' not in matn:
        return matn
    return ' '.join(
        QAYTA_TIKLASH.get(soz, soz) if '?' in soz else soz
        for soz in matn.split(' ')
    )


