JADVAL = {
    'а': 'a', 'б': 'b', 'в': 'v', 'г': 'g', 'д': 'd', 'ж': 'j', 'з': 'z',
    'и': 'i', 'й': 'y', 'к': 'k', 'л': 'l', 'м': 'm', 'н': 'n', 'о': 'o',
    'п': 'p', 'р': 'r', 'с': 's', 'т': 't', 'у': 'u', 'ф': 'f', 'х': 'x',
    'ц': 'ts', 'ч': 'ch', 'ш': 'sh', 'щ': 'sh', 'ъ': "'", 'ы': 'i',
    'ь': '', 'э': 'e', 'ю': 'yu', 'я': 'ya', 'ё': 'yo',
    'ў': "o'", 'қ': 'q', 'ғ': "g'", 'ҳ': 'h',
}

# `е` unlidan keyin yoki so'z boshida `ye` bo'ladi: Тешабоев -> Teshaboyev.
UNLILAR = set('аеёиоуўэюяы')

# Manba fayldagi turli tutuq belgilari bitta ko'rinishga keltiriladi.
TUTUQ_BELGILARI = str.maketrans({
    '‘': "'", '’': "'", 'ʻ': "'", 'ʼ': "'",
    'ʽ': "'", '′': "'", '´': "'", '`': "'",
    '“': '"', '”': '"', '–': '-', '—': '-',
})


def _kirillmi(ch):
    return ch.lower() in JADVAL


def lotinga(matn):
    """Kirill yozuvidagi matnni lotin yozuviga o'giradi.

    Lotin harflari o'zgarmaydi, shu sababli aralash yozilgan matnlar ham
    to'g'ri ishlanadi (manba faylda shunday F.I.O. yozuvlari bor).
    """
    natija = []
    for i, ch in enumerate(matn):
        past = ch.lower()
        if past == 'е':
            oldingi = matn[i - 1].lower() if i else ''
            # "ее" birikmasi o'zlashma so'zlarda "ee" bo'lib qoladi: реестр -> reestr.
            chiqish = 'ye' if (not oldingi or oldingi in UNLILAR) and oldingi != 'е' else 'e'
        elif past in JADVAL:
            chiqish = JADVAL[past]
        else:
            natija.append(ch)
            continue

        if ch.isupper() and chiqish:
            keyingi = matn[i + 1] if i + 1 < len(matn) else ''
            # Keyingi harf kichik bo'lsa faqat bosh harf katta bo'ladi
            # ("Ёшлар" -> "Yoshlar"), aks holda butunlay katta ("ЁШЛАР" -> "YOSHLAR").
            if keyingi and _kirillmi(keyingi) and keyingi.islower():
                chiqish = chiqish[0].upper() + chiqish[1:]
            else:
                chiqish = chiqish.upper()
        natija.append(chiqish)
    return ''.join(natija)


def tozala(qiymat, bosh_harf=False):
    """Yacheykadan olingan matnni to'liq tozalaydi.

    Kodirovka tuzatiladi, kirill lotinga o'giriladi, tutuq belgilari va
    ortiqcha bo'shliqlar bir xil ko'rinishga keltiriladi.
    """
    if qiymat is None:
        return ''
    matn = ' '.join(str(qiymat).translate(TUTUQ_BELGILARI).split())
    if not matn:
        return ''
    if bosh_harf:
        matn = matn.upper()
    matn = lotinga(kodirovkani_tuzat(matn))
    # "Ў" + "Ъ" kabi birikmalar ikkita tutuq belgisini beradi (Нўъмонова),
    # ular bittaga keltiriladi.
    return re.sub(r"''+", "'", matn)


def kalit(matn):
    """Matndan barqaror kod yasaydi: "Saҳovat ko'mak" -> "sahovat_komak"."""
    lotin = lotinga(str(matn)).lower().replace("'", '')
    return re.sub(r"[^a-z0-9]+", '_', lotin).strip('_')
